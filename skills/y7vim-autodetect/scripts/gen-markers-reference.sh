#!/usr/bin/env bash
# Regenerates references/extra-root-markers.md by parsing the installed
# LazyVim source. Run after a LazyVim upgrade to keep the table current.
set -euo pipefail

LAZYVIM_SRC="${LAZYVIM_SRC:-$HOME/.local/share/nvim/lazy/LazyVim}"
EXTRAS_DIR="$LAZYVIM_SRC/lua/lazyvim/plugins/extras/lang"
OUT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/references/extra-root-markers.md"

if [ ! -d "$EXTRAS_DIR" ]; then
  echo "LazyVim source not found at: $EXTRAS_DIR" >&2
  exit 1
fi

{
  echo "# LazyVim lang extras — ft/root triggers"
  echo
  echo "Auto-generated by \`scripts/gen-markers-reference.sh\` from the"
  echo "installed LazyVim source. Do not edit by hand — regenerate instead."
  echo
  echo "| Extra | Filetype(s) | Root markers |"
  echo "|---|---|---|"
  for f in "$EXTRAS_DIR"/*.lua; do
    name=$(basename "$f" .lua)
    ft=$(grep -oE 'ft = "[^"]+"' "$f" | head -1 | grep -oE '"[^"]+"' | tr -d '"' || true)
    markers=$(awk '/root = \{/,/\}/' "$f" | grep -oE '"[^"]+"' | tr -d '"' || true)
    markers_joined=$(echo "$markers" | paste -sd ',' - 2>/dev/null | sed 's/,/, /g')
    echo "| $name | ${ft:-—} | ${markers_joined:-—} |"
  done
} > "$OUT"

echo "Wrote $OUT"
